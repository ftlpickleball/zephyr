"""Generate modules/hal_nordic/nrfx_cmake.bzl from modules/hal_nordic/nrfx/CMakeLists.txt.

The fork's hand-written hal_nordic BUILD drifted from CMake (missing GRTC,
SPIM, CRACEN, the nRF54LM20 chip defines). This mirrors every
zephyr_compile_definitions_ifdef and CONFIG_NRFX_* zephyr_library_sources_ifdef
line instead.

  bazel run //scripts/ftlp:cmake_tables           # rewrite the .bzl
  bazel test //scripts/ftlp:cmake_tables_test     # fails when it is stale
"""

from __future__ import annotations

import os
import pathlib
import re
import sys

CMAKE = "modules/hal_nordic/nrfx/CMakeLists.txt"
OUT = "modules/hal_nordic/nrfx_cmake.bzl"

_DEFS = re.compile(r"^zephyr_compile_definitions_ifdef\(\s*(CONFIG_\w+)\s+([^)]*)\)", re.M)
_SRCS = re.compile(r"^zephyr_library_sources_ifdef\(\s*(CONFIG_NRFX_\w+)\s+\$\{SRC_DIR\}/(\S+)\s*\)", re.M)


def parse_defines(cmake: str) -> dict[str, list[str]]:
    """Kconfig symbol -> global compile definitions, in CMake order."""
    out: dict[str, list[str]] = {}
    for sym, body in _DEFS.findall(cmake):
        for d in body.split():
            out.setdefault(sym, [])
            if d not in out[sym]:
                out[sym].append(d)
    return out


def parse_driver_sources(cmake: str) -> dict[str, list[str]]:
    """CONFIG_NRFX_* symbol -> sources under nrfx/drivers/src."""
    out: dict[str, list[str]] = {}
    for sym, src in _SRCS.findall(cmake):
        out.setdefault(sym, []).append(src)
    return out


def _dict(name: str, table: dict[str, list[str]]) -> list[str]:
    lines = [f"{name} = {{"]
    for key, vals in table.items():
        items = ", ".join(f'"{v}"' for v in vals)
        lines.append(f'    "{key}": [{items}],')
    lines.append("}")
    return lines


def render(cmake: str) -> str:
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        f"# GENERATED by scripts/ftlp/cmake_tables.py from {CMAKE}. Do not edit.",
        "",
        *_dict("NRFX_COMPILE_DEFINITIONS", parse_defines(cmake)),
        "",
        *_dict("NRFX_DRIVER_SOURCES", parse_driver_sources(cmake)),
        "",
        "def nrfx_compile_definitions():",
        '    """One select per Kconfig symbol, concatenated."""',
        "    out = []",
        "    for sym, defs in NRFX_COMPILE_DEFINITIONS.items():",
        "        out += select({",
        '            "@zephyr_kconfig//:" + sym + "=true": defs,',
        '            "//conditions:default": [],',
        "        })",
        "    return out",
        "",
        "def nrfx_driver_filegroups(prefix):",
        '    """Declares <prefix>_<symbol> filegroups; returns their labels."""',
        "    labels = []",
        "    for sym, srcs in NRFX_DRIVER_SOURCES.items():",
        '        name = prefix + "_" + sym.lower()',
        "        native.filegroup(",
        "            name = name,",
        "            srcs = select({",
        '                "@zephyr_kconfig//:" + sym + "=true": ["nrfx/drivers/src/" + s for s in srcs],',
        '                "//conditions:default": [],',
        "            }),",
        "        )",
        '        labels.append(":" + name)',
        "    return labels",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    root = pathlib.Path(os.environ.get("BUILD_WORKSPACE_DIRECTORY", os.getcwd()))
    (root / OUT).write_text(render((root / CMAKE).read_text()))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
